#!/usr/bin/env bash
# Create an Entra App Registration in the GenAquarius tenant for LOCAL SSO + 2FA testing,
# then write the credentials into server/.env so "Sign in with Microsoft" works on localhost.
#
# Prereq: you are signed in to the GenAquarius tenant:  az login
# Run from app/deploy:  bash setup-local-sso.sh
set -euo pipefail

REDIRECT="http://localhost:4000/api/auth/azure/callback"
DISPLAY="GA Costing — Local Dev"

echo "Creating app registration…"
APP_ID=$(az ad app create \
  --display-name "$DISPLAY" \
  --web-redirect-uris "$REDIRECT" \
  --sign-in-audience AzureADMyOrg \
  --enable-id-token-issuance true \
  --query appId -o tsv)

echo "Creating client secret…"
SECRET=$(az ad app credential reset --id "$APP_ID" --display-name local --query password -o tsv)
TENANT=$(az account show --query tenantId -o tsv)

ENVFILE="$(dirname "$0")/../server/.env"
# strip any previous AZURE_* lines, then append fresh ones
grep -v '^AZURE_' "$ENVFILE" > "$ENVFILE.tmp" 2>/dev/null || true
mv "$ENVFILE.tmp" "$ENVFILE" 2>/dev/null || true
cat >> "$ENVFILE" <<EOF

# --- Entra SSO (local dev) — generated by setup-local-sso.sh ---
AZURE_TENANT_ID=$TENANT
AZURE_CLIENT_ID=$APP_ID
AZURE_CLIENT_SECRET=$SECRET
AZURE_REDIRECT_URI=$REDIRECT
EOF

echo ""
echo "Done. Wrote AZURE_* to server/.env"
echo "  Tenant:   $TENANT"
echo "  Client:   $APP_ID"
echo "Now restart the API and open http://localhost:5173 → 'Sign in with Microsoft'."
echo "Sign in as sandeep.minocha@genaquarius.com (MFA prompt comes from Microsoft)."
